-- One-way reset requested by the product owner: legacy student-verification
-- facts are not migrated, backed up, shadow-read, or retained as compatibility
-- evidence. User accounts, QQ bindings, phone state, admission policy and
-- general business data are deliberately outside this purge.

-- Drain every in-flight writer before collecting object keys or deleting
-- evidence. These locks are intentionally broad and one-shot: without them an
-- old application transaction could commit a profile, credential or release
-- action after the corresponding DELETE/UPDATE had already run.

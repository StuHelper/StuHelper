CREATE TRIGGER reject_buaa_upsert_roster_legacy_write
BEFORE INSERT OR UPDATE ON academic.buaa_students
FOR EACH ROW EXECUTE FUNCTION public.reject_retired_student_verification_write();

CREATE TRIGGER reject_unscoped_student_credential_legacy_write
BEFORE INSERT OR UPDATE ON public.user_verification_credentials
FOR EACH ROW
WHEN (NEW.verification_application_id IS NULL)
EXECUTE FUNCTION public.reject_retired_student_verification_write();

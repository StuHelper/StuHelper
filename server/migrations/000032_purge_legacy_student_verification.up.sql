-- Keep a still-running old binary from recreating deleted facts while the new
-- release replaces it. The target student-verification service never writes
-- the retired tables, and every target credential is tied to a target
-- verification application. This database fence is intentionally permanent;
-- application rollback may not re-enable legacy writers.
CREATE FUNCTION public.reject_retired_student_verification_write()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'retired student-verification write path is permanently disabled'
        USING ERRCODE = '55000';
END
$$;

CREATE TRIGGER reject_user_profiles_legacy_write
BEFORE INSERT OR UPDATE ON public.user_profiles
FOR EACH ROW EXECUTE FUNCTION public.reject_retired_student_verification_write();

CREATE TRIGGER reject_user_identities_legacy_write
BEFORE INSERT OR UPDATE ON public.user_identities
FOR EACH ROW EXECUTE FUNCTION public.reject_retired_student_verification_write();

CREATE TRIGGER reject_freshman_applications_legacy_write
BEFORE INSERT OR UPDATE ON public.freshman_verification_applications
FOR EACH ROW EXECUTE FUNCTION public.reject_retired_student_verification_write();

CREATE TRIGGER reject_freshman_materials_legacy_write
